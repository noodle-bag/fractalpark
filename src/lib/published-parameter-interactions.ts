const interactions = new Map(REVIEWED.map(([id, entries]) => [id, new Map(entries.map(
  ([slot, kind, hint]) => [slot, { kind, hint }],
))]));

export function resolveParameterInteraction(
  formulaId: string,
  parameter: PublishedFormulaParameterDescriptorV1,
): { kind: ParameterInteractionKind; hint?: ParameterInteractionHint; integer?: boolean } | null {
  if (parameter.type !== 'complex' || parameter.uniformName !== `frmV1_${parameter.slotName}`) return null;
  const interaction = interactions.get(formulaId)?.get(parameter.slotName);
  if (!interaction) return null;
  return {
    ...interaction,
    integer: interaction.kind === 'times' || (
      interaction.kind === 'real' && ['iterationLimit', 'switch_at', 'switchAt'].includes(parameter.slotName)
    ),
  };
}
